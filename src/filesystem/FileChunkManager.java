
// FileChunkManager

package filesystem; // Declares the package where this file-system utility resides

import java.io.File; // Imports Java File class to handle local disk references
import java.io.FileInputStream; // Imports FileInputStream to read binary streams from files
import java.io.FileOutputStream; // Imports FileOutputStream to write or append binary streams to disk
import java.io.IOException; // Imports IOException to handle disk reading/writing errors safely

public class FileChunkManager {
    
    // Defines the standard chunk size as 8KB (8,192 bytes) to optimize memory usage 
    // and network packet streaming without overflowing socket buffers.
    public static final int CHUNK_SIZE = 8192;

    /**
     * Reads a file from disk, breaks it down into sequential 8KB byte chunks, 
     * and streams each chunk to a callback function for network transmission.
     * @param file The target file to split.
     * @param callback The callback interface handling each generated byte chunk.
     */
    public void splitFileIntoChunks(File file, ChunkCallback callback) {
        // Guard clause: exit immediately if the file is null, doesn't exist, or is a directory
        if (file == null || !file.exists() || file.isDirectory()) {
            return;
        }

        // Try-with-resources block ensures the file input stream automatically closes after reading
        try (FileInputStream fis = new FileInputStream(file)) {
            
            // Allocate a reusable 8KB byte array buffer
            byte[] buffer = new byte[CHUNK_SIZE];
            int bytesRead;
            int sequenceNumber = 0; // Tracks the order of chunks for safe reassembly on the receiving peer
            
            // Read file iteratively in blocks until End-Of-File (-1) is reached
            while ((bytesRead = fis.read(buffer)) != -1) {
                byte[] chunk;
                
                // Check if the current block read a full 8KB chunk
                if (bytesRead == CHUNK_SIZE) {
                    chunk = buffer; // Use the full buffer directly
                } else {
                    // For the final remaining fractional chunk, trim the array to the exact bytes read
                    chunk = new byte[bytesRead];
                    System.arraycopy(buffer, 0, chunk, 0, bytesRead);
                }
                
                // Pass the chunk, its sequence ID, and the file name to the network callback
                callback.onChunkReady(chunk, sequenceNumber++, file.getName());
            }
        } catch (IOException e) {
            e.printStackTrace(); // Print stack trace if disk reading fails
        }
    }

    /**
     * Appends an incoming byte chunk to the destination file during peer transmission reassembly.
     * @param data The raw byte chunk received from the network socket.
     * @param destinationPath The path where the file is being reassembled on the hard disk.
     */
    public void assembleChunkAndWrite(byte[] data, String destinationPath) {
        // Guard clause against null parameters
        if (data == null || destinationPath == null) {
            return;
        }
        
        // FileOutputStream with 'true' as the second parameter enables 'append' mode,
        // allowing chunks to be written sequentially and supporting resumed transfers if interrupted.
        try (FileOutputStream fos = new FileOutputStream(destinationPath, true)) {
            fos.write(data); // Write the byte chunk to disk
            fos.flush();     // Force-flush the stream buffer to storage
        } catch (IOException e) {
            e.printStackTrace(); // Print stack trace if disk writing fails
        }
    }

    /**
     * Callback interface used to stream chunks out to the network transmission handler
     * as they are read off the local hard drive.
     */
    public interface ChunkCallback {
        void onChunkReady(byte[] chunk, int sequenceNumber, String fileName);
    }
}
